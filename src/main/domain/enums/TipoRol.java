
package domain.enums;

/**
 * TipoRol
 *
 * Define los distintos roles que pueden desempenar los secuaces
 * de la organizacion criminal durante la ejecucion de misiones.
 */
public enum TipoRol {

    /** Secuaz especializado en la conduccion de vehiculos. */
    CONDUCTOR,

    /** Secuaz especializado en operaciones de asalto. */
    ASALTO,

    /** Secuaz especializado en sistemas informaticos. */
    HACKER,

    /** Secuaz especializado en la apertura de cerraduras. */
    CERRAJERO,

    /** Secuaz especializado en negociacion. */
    NEGOCIADOR
}
